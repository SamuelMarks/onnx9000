class TraceableCallable(Protocol):
    """Protocol for callables traced or exported by torch_like."""

    def __call__(self, *args: Tensor, **kwargs: Tensor) -> Tensor:
        """Invoke traceable model or function."""


class jit:
    """PyTorch-compatible JIT tracing and scripting namespace."""

    @staticmethod
    def trace(func: TraceableCallable, example_inputs: Tensor | tuple[Tensor, ...]) -> GraphBuilder:
        """Trace a function or module with example inputs.

        Args:
            func: Target callable or nn.Module to trace.
            example_inputs: Example input tensor or tuple of tensors.

        Returns:
            Traced GraphBuilder instance.
        """
        return trace(func, example_inputs)

    @staticmethod
    def script(func: TraceableCallable) -> GraphBuilder:
        """Compile a function or module via AST/TorchScript translation.

        Args:
            func: Target callable to script.

        Returns:
            Compiled GraphBuilder instance.
        """
        return script(func)


class onnx:
    """PyTorch-compatible ONNX export namespace."""

    @staticmethod
    def export(
        model: TraceableCallable,
        args: Tensor | tuple[Tensor, ...],
        f: str | None = None,
        input_names: list[str] | None = None,
        output_names: list[str] | None = None,
        opset_version: int = 18,
    ) -> None:
        """Export a frontend model to an ONNX file.

        Args:
            model: Module or callable to export.
            args: Example input tensor or tuple of tensors.
            f: Destination file path.
            input_names: Optional input node names.
            output_names: Optional output node names.
            opset_version: Target ONNX opset version.
        """
        export(
            model,
            args,
            f,
            input_names=input_names,
            output_names=output_names,
            opset_version=opset_version,
        )


